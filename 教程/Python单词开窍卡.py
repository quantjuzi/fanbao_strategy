# Python 单词开窍卡：不用背，看见会猜就行
# 手机上看这个文件，每行都是一个"单词 + 为什么这么叫"

# ============================================================
# 一、核心动作词（代码里出现最多，先记这 15 个）
# ============================================================
# def       = define 定义      → 告诉电脑"我要造一个新功能"
# return    = 返回             → 把结果交还给出钱的人
# import    = 导入             → 从工具箱里拿工具
# from      = 从哪来           → 说明工具放在哪个箱子里
# class     = 类               → 一张图纸，用图纸造出对象
# self      = 我自己           → 这个对象自己
# None      = 空               → 什么都没有
# True      = 真               → 是
# False     = 假               → 否
# if        = 如果             → 岔路口，条件成立走这条路
# else      = 否则             → 岔路口，条件不成立走另一条
# for       = 对每个           → 挨个点名，点名完就停
# in        = 在...里          → 从容器里一个个拿出来
# while     = 只要...就一直    → 一直转，直到条件不成立
# len       = length 长度      → 数一数有几个

# ============================================================
# 二、数据名词（存东西的容器）
# ============================================================
# list      = 列表             → 一张按顺序写的清单
# dict      = 字典             → 查词条，查出解释（键=值）
# set       = 集合             → 一袋子不重样的东西
# index     = 索引             → 第几号位
# append    = 追加             → 清单末尾再加一个人
# key/value = 键/值            → 词条/解释

# ============================================================
# 三、pandas 常用词（下一阶段每天见）
# ============================================================
# DataFrame = 数据框          → 就是一张 Excel 表
# column    = 列               → 竖着的一栏（像表头那栏）
# row       = 行               → 横着的一行
# head      = 头部             → 看前几行
# tail      = 尾部             → 看后几行
# shape     = 形状             → 这张表几行几列
# drop      = 丢掉             → 丢掉不要的行或列
# merge     = 合并             → 把两张表按某列拼起来
# filter    = 过滤             → 只留下符合条件的
# groupby   = 按...分组        → 把相同类别的放一组，再汇总
# mean      = 平均             → 平均值
# median    = 中位数           → 排中间的那个数
# std       = 标准差           → 数据抖不抖（波动大不大）
# sort_values = 按数值排序     → 从小到大或从大到小排
# unique    = 不重复的         → 去重后还剩哪些
# value_counts = 数次数        → 每个值各出现几次
# fillna    = 填空             → 把空值填上
# dropna    = 丢空             → 有空值的行直接丢掉
# loc       = 按名字找         → 按行名/列名取值
# iloc      = 按位置找         → 按第几行第几列取值
# read_csv  = 读CSV            → 把文件读成表格
# to_csv    = 存CSV            → 把表格存成文件

# ============================================================
# 四、看见陌生单词的三步猜词法
# ============================================================
# 1. 先看词根猜中文
#    append 像"加"，merge 像"合"，drop 像"丢"
# 2. 再看有没有括号 ()
#    名字后面有 ()  = 一个动作（做了会返回结果）
#    名字没有 ()    = 一个名词（数据或属性）
# 3. 最后对中文注释
#    仓库代码每行都有中文注释，先读中文，再对应单词

