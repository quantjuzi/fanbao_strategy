# 2026-08-12 DataFrame 复制与布尔条件（手机复习版）
# 三句话记住：
# 1. df = raw 是贴标签，不是复印
# 2. 印新表要接住，原地改会动原表
# 3. | 是"或者"，& 是"并且"，数个数用 astype(int).sum()

import pandas as pd

# ============================================================
# 一、贴标签 vs 复印
# ============================================================
raw = pd.DataFrame({"学生": ["小明", "小红"], "语文": [90, 85]})
df = raw                      # 给同一张表贴第二个名字，没有复制
df["备注"] = "通过"           # 在 df 上加一列，其实改的就是 raw
print(raw.columns.tolist())   # raw 也有"备注"列，因为它们是同一张表

fanbao = raw.copy()           # copy() 才是真的复印一张新表
fanbao["备注"] = "复印版"
print(raw["备注"].tolist())      # 原表还是"通过"
print(fanbao["备注"].tolist())   # 新表是"复印版"

# ============================================================
# 二、印新表要接住
# ============================================================
df2 = pd.DataFrame({"代码": [1, 1, 2], "收盘": [10, 10, 12]})
df2 = df2.drop_duplicates()   # 不接住等于白做
print(df2)

# ============================================================
# 三、布尔条件：| 或，& 且
# ============================================================
df3 = pd.DataFrame({
    "股票": ["A", "B", "C", "D"],
    "涨停": [True, False, True, False],
    "停牌": [False, False, True, False],
})
both = df3["涨停"] & df3["停牌"]       # 同时满足
either = df3["涨停"] | df3["停牌"]     # 至少一个满足
print(both.tolist())                  # [False, False, True, False]
print(either.tolist())                # [True, False, True, False]
print(either.astype(int).sum())       # 2，数出满足条件的行数

# 重点：pandas 里不能用 and / or，必须用 & / |
