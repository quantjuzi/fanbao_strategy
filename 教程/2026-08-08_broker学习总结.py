# 二、读代码三步法
# ============================================================
# 1. 先看 def 函数名(...)：函数名就是它想算什么
# 2. 再看 -> float：说明最后返回一个数字
# 3. 只看 return 那一行：把它念成中文

# ============================================================
# 三、高频英文单词（配对记，不背单词）
# ============================================================
# buy / sell        = 买 / 卖
# fee               = 费用
# commission        = 佣金
# transfer          = 过户
# stamp duty        = 印花税
# slippage          = 滑点
# amount            = 成交额
# price             = 价格
# qty               = 数量
# rate              = 费率
# round trip        = 一买一卖
# net               = 净（扣完后）
# reference         = 参考
#
# 函数名 = 英文单词拼起来，翻成中文就是注释：
# buy_fee           = buy 买 + fee 费用 = 买入费用
# round_trip_cost_pct = 一买一卖 + 成本 + 百分比 = 往返成本百分比
# net_pnl           = net 净 + pnl 盈亏 = 实际盈亏

# ============================================================
# 四、今天讲到的函数（逐行中文）
# ============================================================
# buy_fill_price    = 买入实际成交价 = 参考价 × (1 + 滑点)，买贵一点
# sell_fill_price   = 卖出实际成交价 = 参考价 × (1 − 滑点)，卖便宜一点
# commission        = 佣金 = 成交额 × 费率 和 5 元，取大的
# transfer_fee      = 过户费 = 成交额 × 费率，没有最低门槛
# buy_fee           = 买入费用 = 佣金 + 过户费（买入不收印花税）
# sell_fee          = 卖出费用 = 佣金 + 过户费 + 印花税
# round_trip_fee    = 总费用 = 买入费用 + 卖出费用
# net_pnl           = 毛利润 − 总费用，全程用带滑点的实际成交价

# ============================================================
# 五、今天踩的坑：小数位数
# ============================================================
# 过户费费率 0.00001 = 万0.1
# 印花税费率 0.0005  = 万5
#
# 口算：1000 元一买一卖
# 佣金      5 + 5 = 10 元
# 过户费    0.01 + 0.01 = 0.02 元
# 印花税    0.5 元
# 总费用    10.52 元

# ============================================================
# 六、今天新懂的三个概念
# ============================================================
# 1. 参考价 vs 实际成交价
#    参考价是你看到的价格，实际成交价是加了滑点后的真实成交价
#
# 2. 函数定义处 vs 调用处
#    buy_fill = self.buy_fill_price(buy_ref) 看不到公式，
#    公式藏在 buy_fill_price 的定义里。
#    调用 = 点菜，定义 = 菜谱
#
# 3. -> 是“返回”
#    -> float 表示这个函数返回一个小数
#    reference_price: float 表示参数应该是小数

