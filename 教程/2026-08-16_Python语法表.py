# ------------------------------------------------------------
# 1. 变量：给数据起名字
# ------------------------------------------------------------
price = 10.5        # 把 10.5 存进 price
shares = 100        # 把 100 存进 shares
cost = price * shares  # 从 price、shares 里取值算乘法，存进 cost

print(cost)  # 1050.0

# 反例：price = 10.5 不能写成 price 10.5，会报语法错误。
# 变量名不能以数字开头：1price 不对，price1 可以。


# ------------------------------------------------------------
# 2. 常用数据类型：先会认，不用背
# ------------------------------------------------------------
# int     整数      例子：100、-5
# float   小数      例子：10.5、0.00025
# str     字符串    例子："涨停"、"000001"
# bool    布尔      例子：True、False
# list    列表      例子：[1, 2, 3]
# dict    字典      例子：{"代码": "000001", "名称": "平安银行"}

# 想看一个东西是什么类型，用 type()
print(type(10))        # <class 'int'>
print(type(10.5))      # <class 'float'>
print(type("涨停"))    # <class 'str'>
print(type(True))      # <class 'bool'>
print(type([1, 2]))    # <class 'list'>
print(type({"a": 1}))  # <class 'dict'>


# ------------------------------------------------------------
# 3. 字符串 + f-string：把变量塞进一句话
# ------------------------------------------------------------
name = "深南电A"
current_price = 10.31

print(f"{name} 现价 {current_price} 元")
# 输出：深南电A 现价 10.31 元

# 反例：f"现价 current_price 元"，没加大括号，
# 会直接打印 current_price 这几个字母，而不是 10.31。


# ------------------------------------------------------------
# 4. 列表：一串数据，从 0 开始数
# ------------------------------------------------------------
prices = [10.1, 10.3, 10.5]

print(prices[0])    # 第一个：10.1
print(prices[1])    # 第二个：10.3
print(prices[-1])   # 最后一个：10.5

prices.append(10.8)  # 在末尾加一个
print(prices)        # [10.1, 10.3, 10.5, 10.8]

# 反例：新手以为 prices[1] 是第一个，其实是第二个，
# 因为索引从 0 开始。这是量化代码里最常踩的坑之一。


# ------------------------------------------------------------
# 5. 字典：键 -> 值，按名字找数据
# ------------------------------------------------------------
stock = {"代码": "000001", "名称": "平安银行"}

print(stock["代码"])   # 000001
print(stock["名称"])   # 平安银行

stock["现价"] = 11.2    # 新增一个键值对
print(stock)            # {'代码': '000001', '名称': '平安银行', '现价': 11.2}

# 反例：stock.代码 不能这样取，字典统一用 stock["代码"]。


# ------------------------------------------------------------
# 6. if / elif / else：判断
# ------------------------------------------------------------
close_price = 10.0
open_price = 9.8

if close_price > open_price:
    print("阳线")          # 收盘比开盘高
elif close_price == open_price:
    print("平盘")          # 相等
else:
    print("阴线")          # 收盘比开盘低

# 注意：
# 判断相等必须写 ==，不能写 =
# elif 是"再判断一次"，不是 else if
# if 后面要冒号，下面的内容要缩进


# ------------------------------------------------------------
# 7. for 循环：重复做
# ------------------------------------------------------------
for i in range(3):
    print(i)  # 0 1 2

# range(3) 生成 0、1、2，不含 3
# 量化里更常见的是遍历每一行：
# for index, row in df.iterrows():
#     print(row["代码"])
# 这里的 index 是行号，row 是这一行数据

# 反例：for i in range(3) 后面没有冒号，会报语法错误。
# 反例：print(i) 不缩进，就不属于 for 循环，只会打印一次。


# ------------------------------------------------------------
# 8. while 循环：满足条件就一直做（先认识，少用）
# ------------------------------------------------------------
count = 0
while count < 3:
    print(count)
    count = count + 1
# 输出 0 1 2

# 坑：while 条件永远成立会死循环，程序卡住。
# 所以先学会 for 就够了。


# ------------------------------------------------------------
# 9. 函数：把一段逻辑打包，起个名字，反复调用
# ------------------------------------------------------------
def calc_return(buy_price, sell_price):
    return (sell_price - buy_price) / buy_price * 100

result = calc_return(10.0, 11.0)
print(result)  # 10.0，表示赚了 10%

# 函数四件套：
# def 函数名(参数):   定义
# return 返回值        把结果交出去
# 函数名(参数)         调用
# return 后面的代码不会执行

# 反例：return 写在函数中间，后面的代码永远不会执行到。


# ------------------------------------------------------------
# 10. lambda：只能写一行的小函数
# ------------------------------------------------------------
add_one = lambda x: x + 1
print(add_one(5))  # 6

# 和普通函数等价：
# def add_one(x):
#     return x + 1
# 量化里常用在 rolling、apply 这种"传一个小逻辑"的地方


# ------------------------------------------------------------
# 11. 类型标注：告诉别人参数和返回值是什么类型
# ------------------------------------------------------------
def calc_return(buy_price: float, sell_price: float) -> float:
    """计算收益率，返回百分比数字"""
    return (sell_price - buy_price) / buy_price * 100

# 冒号后面的 float 是"参数类型"
# 箭头后面的 float 是"返回类型"
# 这只是给人看的提示，Python 不强制检查


# ------------------------------------------------------------
# 12. 类 + dataclass：把一批参数打包成一个配置
# ------------------------------------------------------------
from dataclasses import dataclass

@dataclass(frozen=True)
class BrokerConfig:
    commission_rate: float = 0.00025   # 佣金费率
    min_commission: float = 5.0        # 最低佣金
    stamp_duty_rate: float = 0.0005    # 印花税费率

cfg = BrokerConfig()
print(cfg.commission_rate)  # 0.00025

# dataclass 会自动生成 __init__，不用手写构造函数
# frozen=True 表示创建后不能改参数，防止回测结果被偷偷改掉

# 反例：如果去掉 frozen=True，后面可以写 cfg.commission_rate = 0.1，
# 同一套回测结果就不可复现了。


