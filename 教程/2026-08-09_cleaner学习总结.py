# ============================================================
# 四、今天最重要的三个概念
# ============================================================
# 1. 变量是"名字标签"，不是"盒子"
#    df = raw 不是复制，是给同一张表贴第二个名字。
#    改 df 那列，raw 也会跟着变。
#    只有 copy() 才是真的复印一张新表。
#
# 2. 印新表 vs 原地改
#    印新表：drop_duplicates()、dropna()
#      原表不动，要写成 df = df.drop_duplicates() 接住
#    原地改：df["列"] = 值
#      直接在原表上动手，想保护原表就先用 df = df.copy()
#    inplace=True 也是原地改
#    判断依据不是"加减法"，是"印新表还是原地改"
#
# 3. -> 和 return 的区别
#    -> pd.DataFrame 是门牌：说明这个函数最后返回一张表
#    return df 才是真的把表交出去
#    门牌只是说明，货是 return 那句话递出来的

# ============================================================
# 五、今天讲到的 cleaner.py 三个函数（中文逐行）
# ============================================================
# 1. run(df)
#    输入：原始表
#    动作：6 步清洗，一步接一步
#    输出：清洗后的表
#    开头 df = df.copy() 先复印，保护原始数据
#    之后每一步都写 df = self.xxx(df)，表示"表换了新版本"
#
# 2. drop_duplicates(df)
#    输入：一张表
#    动作：删掉完全重复的行
#    输出：去掉重复后的新表
#    before = len(df) 先记住行数
#    删完再数一次，两次的差 = 重复行数量
#    df = df.drop_duplicates() 必须接住，不接住等于白做
#
# 3. detect_suspensions(df)
#    输入：一张表
#    动作：判断哪些行像停牌，标记出来
#    输出：多了 is_suspended 列的表
#    停牌条件（满足任意一个就标记）：
#    a. 成交量 <= 阈值（volume <= volume_threshold）
#    b. 开盘价 = 收盘价 = 昨收价，而且成交量极小
#    | 表示"或者"，& 表示"并且"
#    cond_susp.astype(int) 把 True/False 变成 1/0
#    cond_susp.sum() 数一数一共有几天停牌

# ============================================================
# 六、新列是怎么加出来的
# ============================================================
# df["is_suspended"] = 条件
#   这一列不存在 -> Python 自动把它加在最右边
#   这一列已经存在 -> 覆盖旧值
#
# df.loc[条件, "列名"] = 值
#   只给符合条件的那些行填值
#   条件就是一张 True/False 筛选牌
#   条件为 True 的行才会被填

# ============================================================
