def 转Markdown(表格: pd.DataFrame) -> str:
    """把 DataFrame 渲染成 Markdown 表格，不依赖 tabulate。"""

    列名 = [str(名称) for 名称 in 表格.columns]
    行 = [
        "| " + " | ".join(列名) + " |",
        "| " + " | ".join(["---"] * len(列名)) + " |",
    ]
    for 值 in 表格.itertuples(index=False, name=None):
        行.append(
            "| " + " | ".join("" if pd.isna(x) else str(x) for x in 值) + " |"
        )
    return "\n".join(行)


def 读取名称(路径: Path | None = None) -> dict[str, str]:
    """读取股票代码到名称的映射；不传路径时返回空映射。"""

    if 路径 is None or not 路径.exists():
        return {}
    数据 = pd.read_csv(路径, encoding="utf-8-sig")
    return dict(
        zip(
            数据["code"].astype(str).str[:6],
            数据["display_name"].astype(str),
        )
    )


def 加载策略模块(路径: Path):
    """动态加载主策略模块。"""

    import importlib.util

    spec = importlib.util.spec_from_file_location("策略模块", 路径)
    if spec is None or spec.loader is None:
        raise ImportError(f"无法导入策略模块：{路径}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def 计算指标(
    数据: pd.DataFrame,
    交易日: pd.Series,
) -> dict[str, float]:
    """按全年统一口径计算候选指标。"""

    样本 = 数据.dropna(
        subset=[
            "买入日期",
            "卖出日期",
            "买入成交价",
            "卖出成交价",
            "净收益率",
            "净盈亏金额",
        ]
    ).copy()
    if 样本.empty:
        raise ValueError("候选交易为空，无法计算指标。")

    if not (
        样本["卖出日期"].gt(样本["买入日期"]).all()
    ):
        raise ValueError("存在卖出日期不晚于买入日期的交易。")

    净收益校验 = (
        样本["净盈亏金额"] / 样本["买入金额"] * 100
        - 样本["净收益率"]
    ).abs()
    if 净收益校验.max() > 1e-8:
        raise ValueError("净收益率与净盈亏金额不一致。")

    盈利 = 样本["净收益率"].gt(0)
    亏损 = 样本["净收益率"].lt(0)
    盈利均值 = float(样本.loc[盈利, "净收益率"].mean())
    亏损均值 = float(样本.loc[亏损, "净收益率"].mean())
    两万元标准化盈亏 = float(样本["净收益率"].sum() * 200)

    日期位置 = {
        pd.Timestamp(日期).normalize(): 位置
        for 位置, 日期 in enumerate(交易日)
    }
    资金变化 = np.zeros(len(交易日) + 1, dtype=int)
    for _, 行 in 样本.iterrows():
        买入日 = pd.Timestamp(行["买入日期"]).normalize()
        卖出日 = pd.Timestamp(行["卖出日期"]).normalize()
        if 买入日 not in 日期位置 or 卖出日 not in 日期位置:
            raise ValueError("存在不在交易日历内的买卖日期。")
        资金变化[日期位置[买入日]] += 1
        资金变化[日期位置[卖出日] + 1] -= 1

    每日持仓数 = np.cumsum(资金变化[:-1])
    有持仓日 = 每日持仓数[每日持仓数 > 0]
    最高资金占用 = float(每日持仓数.max() * 20_000)
    平均交易日占用资金 = float(每日持仓数.mean() * 20_000)
    平均持仓日占用资金 = float(有持仓日.mean() * 20_000)
    区间资金收益率 = 两万元标准化盈亏 / 最高资金占用
    复利年化 = (
        ((1 + 区间资金收益率) ** (252 / len(交易日)) - 1) * 100
    )

    return {
        "交易数": float(len(样本)),
        "净胜率": float(盈利.mean() * 100),
        "平均净收益率": float(样本["净收益率"].mean()),
        "平均盈利": 盈利均值,
        "平均亏损": 亏损均值,
        "盈亏比": (
            盈利均值 / abs(亏损均值)
            if 盈利均值 and 亏损均值
            else float("nan")
        ),
        "两万元标准化盈亏": 两万元标准化盈亏,
        "逐笔实际盈亏": float(样本["净盈亏金额"].sum()),
        "最高资金占用": 最高资金占用,
        "平均交易日占用资金": 平均交易日占用资金,
        "平均持仓日占用资金": 平均持仓日占用资金,
        "复利年化": 复利年化,
    }


def 指标行(名称, 样本, 计算指标, 交易日):
    if 样本.empty:
        return {"阶段": 名称, "交易数": 0}
    指标 = 计算指标(样本, 交易日)
    return {
        "阶段": 名称,
        "交易数": int(指标["交易数"]),
        "净胜率": round(指标["净胜率"], 2),
        "平均净收益率": round(指标["平均净收益率"], 4),
        "盈亏比": round(指标["盈亏比"], 4),
        "两万元标准化盈亏": round(指标["两万元标准化盈亏"], 0),
        "复利年化": round(指标["复利年化"], 2),
        "最高资金占用": round(指标["最高资金占用"], 0),
    }


def 写明细(名称: str, 样本: pd.DataFrame, 名称映射表: dict[str, str]) -> str:
    明细目录.mkdir(parents=True, exist_ok=True)
    数据 = 样本.copy()
    数据["证券代码"] = 数据["code"].astype(str).str[:6]
    数据["证券名称"] = 数据["证券代码"].map(名称映射表).fillna("")
    数据["买入日期"] = pd.to_datetime(数据["买入日期"]).dt.strftime("%Y-%m-%d")
    数据["卖出日期"] = pd.to_datetime(数据["卖出日期"]).dt.strftime("%Y-%m-%d")
    数据 = 数据.sort_values(["买入日期", "证券代码"], kind="stable")
    内容 = [
        f"# {名称}",
        "",
        "- 研究区间：2026-01-01 至 2026-09-30",
        f"- 交易数：{len(数据)}",
        "",
        "| 证券代码 | 证券名称 | 买入日期 | 买入价格 | 卖出日期 | 卖出价格 | 净收益率 | 净盈亏金额 |",
        "| --- | --- | --- | ---: | --- | ---: | ---: | ---: |",
    ]
    for _, 行 in 数据.iterrows():
        内容.append(
            f"| {行['证券代码']} | {行['证券名称']} | {行['买入日期']} | "
            f"{float(行['买入成交价']):.4f} | {行['卖出日期']} | "
            f"{float(行['卖出成交价']):.4f} | "
            f"{float(行['净收益率']):.2f}% | "
            f"{float(行['净盈亏金额']):,.2f} |"
        )
    内容.extend(["", "返回：[反包策略研究](../../文档/反包策略研究_2026.md)", ""])
    安全名 = (
        名称.replace("<", "小于")
        .replace(">", "大于")
        .replace("/", "-")
        .replace("%", "")
        .replace("+", "加")
        .replace(" ", "")
    )
    文件 = 明细目录 / f"{安全名}_股票明细.md"
    文件.write_text("\n".join(内容), encoding="utf-8")
    return f"../结果/反包研究明细/{安全名}_股票明细.md"


def 对比表(
    基准样本: pd.DataFrame,
    条件列表: list[tuple[str, pd.DataFrame]],
    计算指标,
    交易日,
) -> pd.DataFrame:
    基准指标 = 计算指标(基准样本, 交易日)
    基准数 = len(基准样本)
    基准收益 = float(基准指标["平均净收益率"])
    行 = []
    for 名称值, 样本 in 条件列表:
        if 样本.empty:
            行.append({"分组": 名称值, "交易数": 0})
            continue
        指标 = 计算指标(样本, 交易日)
        变化 = float(指标["平均净收益率"]) - 基准收益
        if 变化 > 0.2:
            方向 = "正向"
        elif 变化 < -0.2:
            方向 = "负向"
        else:
            方向 = "中性"
        行.append(
            {
                "分组": 名称值,
                "交易数": int(指标["交易数"]),
                "样本变化": int(指标["交易数"]) - 基准数,
                "净胜率": round(指标["净胜率"], 2),
                "平均净收益率": round(指标["平均净收益率"], 4),
                "收益变化": round(变化, 4),
                "结论": 方向,
            }
        )
    return pd.DataFrame(行)


