# ==================== 3. 数据清洗 ====================

# 本步目的：
# 把原始数据转换成后续计算可以稳定使用的标准格式。
# 输入：原始 DataFrame。
# 输出：清洗后的 df 和一份清洗审计信息。
# 实现要点：
# 日期、数值类型、重复行、无效价格、停牌行和缺失值必须在计算信号前处理。
# 常见错误：
# 没检查字段就直接计算，或者删除了数据却不记录删除了多少。

def 清洗数据(原始数据: pd.DataFrame) -> tuple[pd.DataFrame, dict[str, Any]]:
    """转换类型、清理无效记录，并返回清洗审计信息。"""

    原始行数 = len(原始数据)
    df = 原始数据.copy()

    # 日期必须转成 datetime，才能在后面排序、shift 和判断买入卖出日期。
    df["time"] = pd.to_datetime(df["time"], errors="coerce")

    # code 是股票代码，统一成字符串，避免前导零丢失。
    df["code"] = df["code"].astype("string").str.strip()

    # 这些字段要进行数值计算，不能保留字符串类型。
    数值字段 = [
        "open",
        "close",
        "volume",
        "money",
        "paused",
        "竞价涨幅",
        "成交额_亿",
        "M14",
    ]
    for column in 数值字段:
        df[column] = pd.to_numeric(df[column], errors="coerce")

    # 正负无穷不是有效行情，统一转换成缺失值。
    df = df.replace([np.inf, -np.inf], np.nan)

    # 关键字段缺失的记录无法正确计算信号或成交价格，因此直接剔除。
    关键非空字段 = [
        "time",
        "code",
        "open",
        "close",
        "volume",
        "money",
        "M14",
        "竞价涨幅",
        "成交额_亿",
    ]

    # 分别生成无效记录掩码，便于最后统计每种删除原因。
    字段缺失 = df[关键非空字段].isna().any(axis=1)
    无效价格 = (df["open"] <= 0) | (df["close"] <= 0)
    无效成交 = (df["volume"] <= 0) | (df["money"] <= 0)
    停牌记录 = df["paused"].fillna(0).ne(0)
    无效记录 = (
        字段缺失
        | 无效价格
        | 无效成交
        | 停牌记录
    )

    删除原因 = {
        "missing": int(字段缺失.sum()),
        "invalid_price": int(无效价格.sum()),
        "invalid_volume": int(无效成交.sum()),
        "paused": int(停牌记录.sum()),
    }
    df = df.loc[~无效记录].copy()

    # 同一只股票同一天只能有一条记录，重复数据会导致 shift 取错日期。
    去重前行数 = len(df)
    df = df.drop_duplicates(subset=["code", "time"], keep="last")
    重复行数 = 去重前行数 - len(df)

    # 先按股票分组，再按日期排序，后面的 shift(-1) 和 shift(-2) 才有意义。
    df = (
        df.sort_values(["code", "time"])
        .reset_index(drop=True)
    )

    清洗审计 = {
        "original_rows": 原始行数,
        "clean_rows": len(df),
        "removed_rows": 原始行数 - len(df),
        "removed_by_reason": 删除原因,
        "duplicate_rows": 重复行数,
        "stock_count": int(df["code"].nunique()),
        "start_date": df["time"].min(),
        "end_date": df["time"].max(),
    }

    print(
        "数据清洗："
        f"{清洗审计['original_rows']} -> {清洗审计['clean_rows']} 行，"
        f"删除 {清洗审计['removed_rows']} 行"
    )
    return df, 清洗审计


# ==================== 4. 计算因子 ====================

# 本步目的：
# 把原始行情转换成策略可以判断的量价因子。
# 输入：清洗后的 df。
# 输出：增加了因子列的 df。
# 实现要点：
# 因子只能使用当前日期及更早的数据；未来数据只能等到后面的买卖日期再取。

def 计算因子(df: pd.DataFrame) -> pd.DataFrame:
    """根据已有行情计算策略所需因子。"""

    结果 = df.copy()

    # 实体涨幅衡量开盘到收盘的强度，单位是百分比。
    结果["实体涨幅"] = (
        结果["close"] / 结果["open"] - 1
    ) * 100

    # 收盘价站上 M14，表示当前趋势位置在中短期均线之上。
    结果["均线之上"] = 结果["close"] > 结果["M14"]

    # 实体涨幅不能过大，防止信号只集中在极端涨跌日。
    结果["实体适中"] = 结果["实体涨幅"].between(-5, 5)

    # 竞价涨幅大于 0，表示当天早盘相对昨收高开。
    结果["竞价高开"] = 结果["竞价涨幅"] > 0

    # 日线数据里用成交额除以成交量，近似得到当天均价。
    结果["均价"] = 结果["money"] / 结果["volume"]
    return 结果


# ==================== 5. 生成信号 ====================

# 本步目的：
# 把多个因子组合成一个当天是否关注的信号。
# 输入：已经计算好因子的 df。
# 输出：增加“信号”列的 df，1 表示满足条件，0 表示不满足。
# 实现要点：
# 信号在 T 日收盘后才能确认，不能使用 T+1 的收盘信息。

def 生成信号(df: pd.DataFrame) -> pd.DataFrame:
    """组合因子条件，生成逐日逐股信号。"""

    结果 = df.copy()
    结果["信号"] = (
        结果["竞价高开"]
        & 结果["实体适中"]
        & 结果["均线之上"]
    ).astype(int)

    print(f"原始信号数量：{int(结果['信号'].sum())}")
    return 结果


# ==================== 6. 确定买卖规则 ====================

# 本步目的：
# 把信号日与实际买入日、卖出日对应起来。
# 输入：带“信号”列的 df。
# 输出：只包含可执行交易的候选列表。
# 实现要点：
# shift(-1) 表示同一只股票的下一行，shift(-2) 表示再下一行。
# 在日线数据中，这分别对应 T+1 和 T+2。

def 确定买卖规则(df: pd.DataFrame) -> pd.DataFrame:
    """给每只股票对齐信号日、买入日和卖出日。"""

    结果 = df.copy()
    分组数据 = 结果.groupby("code", sort=False)

    # T 日信号出现后，T+1 开盘作为买入参考价。
    结果["买入日期"] = 分组数据["time"].shift(-1)
    结果["买入参考价"] = 分组数据["open"].shift(-1)

    # T+2 的均价作为卖出参考价，具体收益率在成本步骤计算。
    结果["卖出日期"] = 分组数据["time"].shift(-2)
    结果["卖出参考价"] = 分组数据["均价"].shift(-2)

    # 只保留真正产生信号的记录。
    候选列表 = 结果.loc[结果["信号"].eq(1)].copy()
    必要交易字段 = [
        "买入日期",
        "买入参考价",
        "卖出日期",
        "卖出参考价",
    ]
    候选列表 = 候选列表.dropna(subset=必要交易字段)

    # 做日期检查，防止最后两天无法取得 T+1 或 T+2 数据。
    候选列表 = 候选列表.loc[
        候选列表["买入日期"].gt(候选列表["time"])
        & 候选列表["卖出日期"].gt(候选列表["买入日期"])
    ].copy()

    print(f"可执行买卖规则后的信号数量：{len(候选列表)}")
    return 候选列表


# ==================== 7. 加入交易成本 ====================

# 本步目的：
# 把理论收益转换成接近真实账户的成交结果。
# 输入：候选交易和策略参数。
# 输出：带滑点、佣金、印花税、过户费和净收益率的交易明细。
# 实现要点：
# 买入价格要加上滑点，卖出价格要减去滑点；
# 佣金和最低佣金在买入和卖出时都要计算。

def 计算交易成本(
    交易记录: pd.DataFrame,
    配置: 策略参数,
) -> pd.DataFrame:
    """计算滑点、费用、毛收益和净收益。"""

    结果 = 交易记录.reset_index(drop=True).copy()

    def 计算单笔交易(单行数据: pd.Series) -> pd.Series:
        买入参考价 = float(单行数据["买入参考价"])
        卖出参考价 = float(单行数据["卖出参考价"])

        # 滑点表示真实成交价与参考价的差异：买入更贵，卖出更便宜。
        买入成交价 = 买入参考价 * (1 + 配置.滑点率)
        卖出成交价 = 卖出参考价 * (1 - 配置.滑点率)

        # A 股通常按 100 股整手交易，先算预算内能买多少整手。
        持仓份额 = (
            int(配置.每笔名义本金 / 买入成交价 / 配置.每手股数)
            * 配置.每手股数
        )

        if 持仓份额 <= 0:
            # 价格太高时，2 万元可能连一手都买不到，这笔交易应跳过。
            return pd.Series(
                {
                    "买入成交价": 买入成交价,
                    "卖出成交价": 卖出成交价,
                    "持仓份额": 0.0,
                    "买入金额": 0.0,
                    "卖出金额": 0.0,
                    "买入佣金": 0.0,
                    "卖出佣金": 0.0,
                    "买入过户费": 0.0,
                    "卖出过户费": 0.0,
                    "印花税": 0.0,
                    "买入费用": 0.0,
                    "卖出费用": 0.0,
                    "总费用": 0.0,
                    "参考收益率": np.nan,
                    "毛收益率": np.nan,
                    "净收益率": np.nan,
                    "毛盈亏金额": 0.0,
                    "净盈亏金额": 0.0,
                }
            )

        买入金额 = 持仓份额 * 买入成交价
        卖出金额 = 持仓份额 * 卖出成交价

        # 佣金取“成交额乘费率”和“最低佣金”中的较大值。
        买入佣金 = max(
            买入金额 * 配置.佣金费率,
            配置.最低佣金,
        )
        卖出佣金 = max(
            卖出金额 * 配置.佣金费率,
            配置.最低佣金,
        )
        买入过户费 = 买入金额 * 配置.过户费率
        卖出过户费 = 卖出金额 * 配置.过户费率

        # 印花税只在卖出时收取。
        印花税 = 卖出金额 * 配置.印花税费率

        买入费用 = 买入佣金 + 买入过户费
        卖出费用 = 卖出佣金 + 卖出过户费 + 印花税

        # 毛盈亏不含费用；净盈亏扣除买入和卖出的全部费用。
        毛盈亏 = 卖出金额 - 买入金额
        净盈亏 = 毛盈亏 - 买入费用 - 卖出费用

        参考收益率 = (
            卖出参考价 / 买入参考价 - 1
        ) * 100
        毛收益率 = 毛盈亏 / 买入金额 * 100
        净收益率 = 净盈亏 / 买入金额 * 100

        return pd.Series(
            {
                "买入成交价": 买入成交价,
                "卖出成交价": 卖出成交价,
                "持仓份额": 持仓份额,
                "买入金额": 买入金额,
                "卖出金额": 卖出金额,
                "买入佣金": 买入佣金,
                "卖出佣金": 卖出佣金,
                "买入过户费": 买入过户费,
                "卖出过户费": 卖出过户费,
                "印花税": 印花税,
                "买入费用": 买入费用,
                "卖出费用": 卖出费用,
                "总费用": 买入费用 + 卖出费用,
                "参考收益率": 参考收益率,
                "毛收益率": 毛收益率,
                "净收益率": 净收益率,
                "毛盈亏金额": 毛盈亏,
                "净盈亏金额": 净盈亏,
            }
        )

    交易成本 = 结果.apply(计算单笔交易, axis=1)
    结果 = pd.concat([结果, 交易成本], axis=1)

    # 不满足整手条件的交易不进入后续组合。
    跳过笔数 = int(结果["持仓份额"].le(0).sum())
    结果 = 结果.loc[结果["持仓份额"].gt(0)].reset_index(drop=True)

    平均成本 = 结果["总费用"].mean()
    print(f"每笔平均交易成本：{平均成本:.2f} 元")
    print(f"因不足一手跳过：{跳过笔数} 笔")
    return 结果


# ==================== 8. 构建组合和仓位 ====================

# 本步目的：
# 把逐笔信号变成每天实际参与的组合，并检查资金是否足够。
# 输入：已完成成本计算的候选交易。
# 输出：每日成交额排名、最终组合和资金审计。
# 实现要点：
# 每天先按成交额排名，再选择前 N 名；
# 并发持仓检查可以避免回测使用超过账户承受能力的资金。

def 构建组合(
    交易记录: pd.DataFrame,
    配置: 策略参数,
    交易日: pd.Series,
) -> tuple[pd.DataFrame, pd.DataFrame, dict[str, float]]:
    """每天选择成交额前 N 名，并按固定名义本金构建组合。"""

    # 同一交易日按成交额从高到低排名。
    排名结果 = 交易记录.copy()
    排名结果["每日排名"] = 排名结果.groupby("time")["成交额_亿"].rank(
        method="first",
        ascending=False,
    )

    组合 = 排名结果.loc[排名结果["每日排名"] <= 配置.组合数量].copy()
    组合 = 组合.sort_values(
        ["买入日期", "time", "code"]
    ).reset_index(drop=True)
    组合["仓位金额"] = 配置.每笔名义本金

    # 建立交易日日历，把买入日期和卖出日期转换成位置编号。
    交易日历 = pd.Index(
        交易日.drop_duplicates().sort_values()
    )
    日期位置 = {date: index for index, date in enumerate(交易日历)}

    起始位置 = 组合["买入日期"].map(日期位置)
    结束位置 = 组合["卖出日期"].map(日期位置) + 1
    if 起始位置.isna().any() or 结束位置.isna().any():
        raise ValueError("组合中存在不在交易日历内的买入或卖出日期。")

    # 用“开始加一、结束减一”的事件法快速计算并发持仓。
    持仓事件 = np.zeros(len(交易日历) + 1, dtype=int)
    资金事件 = np.zeros(len(交易日历) + 1, dtype=float)
    所需资金 = (
        组合["买入金额"] + 组合["买入费用"]
    ).to_numpy()
    np.add.at(持仓事件, 起始位置.astype(int), 1)
    np.add.at(持仓事件, 结束位置.astype(int), -1)
    np.add.at(资金事件, 起始位置.astype(int), 所需资金)
    np.add.at(资金事件, 结束位置.astype(int), -所需资金)
    并发持仓数 = np.cumsum(持仓事件[:-1])
    并发占用资金 = np.cumsum(资金事件[:-1])

    最高并发持仓 = int(并发持仓数.max())
    最高资金占用 = float(并发占用资金.max())
    if 最高资金占用 > 配置.初始资金:
        raise ValueError(
            "最高并发持仓所需资金超过初始资金："
            f"{最高资金占用:,.0f} > {配置.初始资金:,.0f}"
        )

    资金审计 = {
        "max_concurrent_positions": 最高并发持仓,
        "max_capital_required": 最高资金占用,
        "initial_capital": 配置.初始资金,
    }

    print(f"组合交易笔数：{len(组合)}")
    print(
        "最高并发持仓："
        f"{最高并发持仓} 个，资金占用 {最高资金占用:,.0f} 元"
    )
    return 排名结果, 组合, 资金审计


# ==================== 9. 计算收益、回撤、夏普 ====================

# 本步目的：
# 把逐笔交易汇总成账户层面的绩效指标。
# 输入：全部候选交易、最终组合和交易日序列。
# 输出：绩效指标字典和每日净值曲线。
# 实现要点：
# 逐笔指标回答“单笔平均好不好”，组合指标回答“按时间持有账户表现如何”。

def 计算绩效(
    交易记录: pd.DataFrame,
    组合: pd.DataFrame,
    交易日: pd.Series,
) -> tuple[dict[str, float], pd.DataFrame]:
    """计算逐笔指标和按卖出日计算的等权组合指标。"""

    # 分别统计全部信号和最终组合，便于比较筛选前后差异。
    全部交易指标 = 计算逐笔指标(交易记录)
    组合交易指标 = 计算逐笔指标(组合)

    # 按卖出日期汇总每日净收益，同一天多笔交易先取平均值。
    每日收益 = (
        组合.groupby("卖出日期")["净收益率"]
        .mean()
        .div(100)
    )

    # 没有交易发生的交易日补 0，防止夏普和净值只统计有交易的日子。
    交易日历 = (
        交易日.drop_duplicates()
        .sort_values()
        .loc[
            lambda values: values.between(
                每日收益.index.min(),
                每日收益.index.max(),
            )
        ]
    )
    每日收益 = 每日收益.reindex(交易日历, fill_value=0.0)

    # 净值从 1 开始逐日累乘，回撤表示净值相对历史最高点的下降比例。
    净值 = (1 + 每日收益).cumprod()
    回撤 = 净值 / 净值.cummax() - 1

    # 年化收益、年化波动率和夏普都用 252 个交易日换算。
    交易天数 = len(每日收益)
    年化收益 = (
        净值.iloc[-1] ** (252 / 交易天数) - 1
        if 交易天数 > 0 and 净值.iloc[-1] > 0
        else np.nan
    )
    年化波动率 = (
        每日收益.std(ddof=1) * np.sqrt(252)
        if 交易天数 > 1
        else np.nan
    )
    夏普 = (
        每日收益.mean() / 每日收益.std(ddof=1) * np.sqrt(252)
        if 交易天数 > 1 and 每日收益.std(ddof=1) > 0
        else np.nan
    )

    指标 = {
        **组合交易指标,
        "全部信号毛收益率": 全部交易指标["平均毛收益率"],
        "全部信号净收益率": 全部交易指标["平均净收益率"],
        "组合毛收益率": 组合交易指标["平均毛收益率"],
        "组合净收益率": 组合交易指标["平均净收益率"],
        "组合净胜率": 组合交易指标["净胜率"],
        "组合平均盈利": 组合交易指标["平均盈利"],
        "组合平均亏损": 组合交易指标["平均亏损"],
        "组合盈亏比": 组合交易指标["盈亏比"],
        "组合累计净盈亏": float(组合["净盈亏金额"].sum()),
        "组合最终净值": float(净值.iloc[-1]),
        "组合最终收益": float((净值.iloc[-1] - 1) * 100),
        "组合最大回撤": float(回撤.min() * 100),
        "组合年化收益": float(年化收益 * 100),
        "组合年化波动率": float(年化波动率 * 100),
        "组合夏普": float(夏普),
        "组合交易日数": float(交易天数),
    }

    净值曲线 = pd.DataFrame(
        {
            "日期": 净值.index,
            "每日净收益率": 每日收益.values,
            "净值": 净值.values,
            "回撤": 回撤.values,
        }
    )
    return 指标, 净值曲线


def 计算逐笔指标(交易记录: pd.DataFrame) -> dict[str, float]:
    """计算逐笔毛收益和净收益指标。"""

    if 交易记录.empty:
        raise ValueError("没有可统计交易。")

    # 毛收益只看价格变化，净收益再扣除手续费、印花税、过户费和滑点。
    毛盈利交易 = 交易记录.loc[交易记录["毛收益率"] > 0, "毛收益率"]
    毛亏损交易 = 交易记录.loc[交易记录["毛收益率"] < 0, "毛收益率"]
    净盈利交易 = 交易记录.loc[交易记录["净收益率"] > 0, "净收益率"]
    净亏损交易 = 交易记录.loc[交易记录["净收益率"] < 0, "净收益率"]

    毛盈利合计 = 毛盈利交易.sum()
    毛亏损合计 = abs(毛亏损交易.sum())
    净盈利合计 = 净盈利交易.sum()
    净亏损合计 = abs(净亏损交易.sum())

    return {
        "交易笔数": float(len(交易记录)),
        "毛胜率": float((交易记录["毛收益率"] > 0).mean() * 100),
        "净胜率": float((交易记录["净收益率"] > 0).mean() * 100),
        "平均毛收益率": float(交易记录["毛收益率"].mean()),
        "平均净收益率": float(交易记录["净收益率"].mean()),
        "平均盈利": float(净盈利交易.mean()) if not 净盈利交易.empty else 0.0,
        "平均亏损": float(净亏损交易.mean()) if not 净亏损交易.empty else 0.0,
        "盈亏比": (
            float(净盈利交易.mean() / abs(净亏损交易.mean()))
            if not 净盈利交易.empty and not 净亏损交易.empty
            else np.nan
        ),
        "毛利润因子": (
            float(毛盈利合计 / 毛亏损合计)
            if 毛亏损合计 > 0
            else np.inf
        ),
        "净利润因子": (
            float(净盈利合计 / 净亏损合计)
            if 净亏损合计 > 0
            else np.inf
        ),
    }


