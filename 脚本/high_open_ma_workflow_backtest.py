# ==================== 11. 检查结果是否合理 ====================

# 本步目的：
# 在相信结果之前，先检查日期、缺失值、异常收益和资金约束。
# 输入：清洗后的 df、组合、逐笔指标和资金审计。
# 输出：一组“通过、警告、失败”的检查文本。
# 实现要点：
# 回测能跑完不代表结果可信，必须做基础合理性检查。

def 验证结果(
    df: pd.DataFrame,
    排名结果: pd.DataFrame,
    组合: pd.DataFrame,
    指标: dict[str, float],
    资金审计: dict[str, float],
) -> list[str]:
    """执行基础合理性检查，返回可读检查结果。"""

    检查结果: list[str] = []

    # 检查时间和价格是否按预期对齐。
    日期顺序正常 = 组合["time"].lt(组合["买入日期"]).all()
    检查结果.append(
        f"{'通过' if 日期顺序正常 else '失败'}：信号日早于买入日"
    )

    持有日期正常 = 组合["买入日期"].lt(组合["卖出日期"]).all()
    检查结果.append(
        f"{'通过' if 持有日期正常 else '失败'}：买入日早于卖出日"
    )

    # 检查交易字段是否完整，以及是否出现重复交易。
    no_missing = not 组合[
        ["买入参考价", "卖出参考价", "净收益率"]
    ].isna().any().any()
    检查结果.append(
        f"{'通过' if no_missing else '失败'}：交易关键字段无缺失"
    )

    no_duplicate_trade = not 组合.duplicated(
        subset=["time", "code"]
    ).any()
    检查结果.append(
        f"{'通过' if no_duplicate_trade else '失败'}：同一股票同一信号日只交易一次"
    )

    # 单笔收益率超过 35% 对短线日线策略不合理，需要人工查看。
    最大绝对收益率 = 组合["净收益率"].abs().max()
    收益范围合理 = 最大绝对收益率 <= 35
    检查结果.append(
        f"{'通过' if 收益范围合理 else '警告'}："
        f"单笔最大绝对净收益率 {最大绝对收益率:.2f}%"
    )

    # 检查成本和资金占用是否符合配置。
    平均成本百分比 = (
        组合["总费用"] / 组合["买入金额"] * 100
    ).mean()
    检查结果.append(f"信息：平均往返费用占买入金额 {平均成本百分比:.4f}%")

    成本为正 = (组合["总费用"] > 0).all()
    检查结果.append(
        f"{'通过' if 成本为正 else '失败'}：所有交易均包含正成本"
    )

    资金检查通过 = (
        资金审计["max_capital_required"]
        <= 资金审计["initial_capital"]
    )
    检查结果.append(
        f"{'通过' if 资金检查通过 else '失败'}："
        f"最高占用资金 {资金审计['max_capital_required']:,.0f} 元，"
        f"初始资金 {资金审计['initial_capital']:,.0f} 元"
    )

    # 样本太少时，胜率和夏普没有足够说服力。
    样本量充足 = len(组合) >= 100
    检查结果.append(
        f"{'通过' if 样本量充足 else '警告'}："
        f"组合样本量 {len(组合)} 笔"
    )

    # 最后检查策略是否真的产生了正收益和可接受的风险。
    净收益为正 = 指标["平均净收益率"] > 0
    检查结果.append(
        f"{'通过' if 净收益为正 else '警告'}："
        f"平均净收益率 {指标['平均净收益率']:.4f}%"
    )

    夏普合理 = 指标["组合夏普"] >= 1
    检查结果.append(
        f"{'通过' if 夏普合理 else '警告'}："
        f"组合夏普 {指标['组合夏普']:.4f}"
    )

    回撤合理 = 指标["组合最大回撤"] > -30
    检查结果.append(
        f"{'通过' if 回撤合理 else '警告'}："
        f"组合最大回撤 {指标['组合最大回撤']:.2f}%"
    )

    交易日数量 = df["time"].nunique()
    检查结果.append(f"信息：清洗后交易日数量 {交易日数量}")
    检查结果.append(f"信息：组合信号候选数量 {len(排名结果)}")

    for 检查项 in 检查结果:
        print(检查项)
    return 检查结果


def 主流程() -> None:
    """按完整量化研究流程执行回测。"""

    # 说明：
    # 第 11 步的检查结果要写进第 10 步的报告，
    # 所以代码先完成检查，再统一输出文件；逻辑上仍按 10、11 两步理解。

    # 第 1 步：建立统一的策略配置。
    配置 = 策略参数()

    # 第 2 步：定位数据文件，然后读取数据。
    路径配置 = 构建路径()
    原始数据 = 读取数据(路径配置.数据文件)

    # 第 3 步：数据清洗，得到可以计算的 df 和清洗审计。
    df, 数据审计 = 清洗数据(原始数据)

    # 第 4 步：计算策略需要的量价因子。
    df = 计算因子(df)

    # 第 5 步：把因子条件组合成信号。
    df = 生成信号(df)

    # 第 6 步：根据信号对齐 T+1 买入和 T+2 卖出。
    候选列表 = 确定买卖规则(df)

    # 第 7 步：加入滑点、佣金、印花税和过户费。
    候选列表 = 计算交易成本(候选列表, 配置)

    # 第 8 步：每天按成交额选前 N 名，并检查并发持仓资金。
    排名结果, 组合, 资金审计 = 构建组合(
        候选列表,
        配置,
        df["time"],
    )

